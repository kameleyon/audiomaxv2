-- ============================================================================
-- 20260809000100_rls_class_rule
--
-- The RLS obligation, expressed as a COMPUTED CLASS RULE rather than a list of
-- table names -- spec §7 preamble, H26-C3.
--
-- Owner: Atlas (schema).  RLS POLICIES themselves are Vault's (`supabase/
-- policies/`, CODEOWNERS:74). This migration writes no policy. It writes the
-- rule that decides which tables need one.
--
-- ---------------------------------------------------------------------------
-- WHY A RULE AND NOT A LIST
--
-- CLAUDE.md constraint 5 and README:335 both say "`voices` is a global
-- catalogue and is exempt" -- an ENUMERATION with exactly one member. Spec §7
-- states the same obligation as a CLASS: "A table is exempt when it carries no
-- user data at all -- not when it happens to be called `voices`." The class
-- grew to two members (`voices`, `voice_langs`) on its first opportunity, and
-- the enumeration in the two governing documents was stale the same day.
--
-- An allowlist is defeatable by ADDITION: append a name and a table leaves the
-- obligation silently. This rule is not a list. Membership is DERIVED from the
-- catalog:
--
--     A table is OBLIGATED to carry RLS iff it can reach user data --
--     i.e. it has a `user_id` column, or it has a foreign key (transitively)
--     to a table that does.
--
-- That is exactly §7's own stated mechanism -- "by `user_id` where the column
-- exists, by join through `documents` otherwise" -- executed instead of
-- described. `voices` has no `user_id` and no outbound FK; `voice_langs` has
-- one FK, to `voices`. Neither reaches user data, so neither is inside the
-- obligation. Adding a catalogue table needs no edit here. Adding a table that
-- touches a user makes this rule fail until RLS is on.
--
-- ---------------------------------------------------------------------------
-- WHERE THE RULE CAN STILL BE DEFEATED, STATED RATHER THAN HIDDEN
--
-- The rule keys on the column NAME `user_id`. A table that stores the user
-- under `owner_id` is invisible to it. That is a real hole and it is not
-- closed by pretending otherwise, so `rls_class_violations()` reports a second
-- kind, `unclassifiable`: a table with no `user_id` and no FK path to one, but
-- carrying a column whose name looks like a user key under another spelling.
-- Such a table is not auto-exempted -- it is FLAGGED for a human decision.
-- Renaming the column therefore moves a table from "obligated" to "needs a
-- ruling", never to "exempt".
--
-- Not covered, and deliberately: a user identifier stored under a name this
-- regex does not anticipate, and RLS enabled with zero policies (which denies
-- everything -- a Vault concern, not an exemption concern).
--
-- ---------------------------------------------------------------------------
-- RECONCILIATION GREP (CLAUDE.md "The reconciliation pass"), run BEFORE editing
--   grep -rn -F "<ident>" CLAUDE.md README.md resources/specs resources/roadmap
--
--   voices                32 files-lines  reconciled -- §7.1 column run is the
--                                         source for 20260809000200
--   voice_langs           32              reconciled -- §7.1a is the source for
--                                         20260809000300
--   assert_rls_class_rule  0              NEW, implementation-only. No document
--   rls_obligated_tables   0              names it and none should: these are
--   rls_class_violations   0              function names, not design facts.
--   set_updated_at         0              Deliberately unreconciled.
--   private (schema)       0              NEW, implementation-only.
--
--   DELIBERATELY UNCHANGED: CLAUDE.md:224 and README.md:335 both name `voices`
--   alone. That is roadmap:689-695 (Owner: Scribe, due 2026-08-15) and it is
--   NOT this migration's to fix -- editing the governing documents was
--   explicitly out of scope this round. Neither line is WRONG about the
--   obligation (neither table carries user data); both are incomplete
--   enumerations, which is precisely the defect this file replaces with a rule.
--
